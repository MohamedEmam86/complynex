def to_iso2(*vals):
    """Set of ISO alpha-2 codes found in the given values (lists, JSON text, ;-joined)."""
    out = set()
    for v in vals:
        for p in _items(v):
            c = _one(p)
            if c:
                out.add(c)
            elif ',' in p:
                out.update(x for x in (_one(q) for q in p.split(',')) if x)
    return out
