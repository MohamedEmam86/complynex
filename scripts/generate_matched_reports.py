class ScreeningReportPDF(FPDF):
    def header(self):
        # Header with Logo
        logo_path = os.path.join(root_dir, 'static', 'images', 'official-logo.png')
        if os.path.exists(logo_path):
            self.image(logo_path, 10, 8, 30)
        
        self.set_font('helvetica', 'B', 15)
        self.cell(80)
        self.cell(30, 10, 'Sanctions Screening Report', 0, 0, 'C')
        self.ln(20)
        
    def footer(self):
        self.set_y(-15)
        self.set_font('helvetica', 'I', 8)
        self.cell(0, 10, f'Page {self.page_no()} | Generated by ComplyNex CMS | {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}', 0, 0, 'C')

def generate_pdf_report(name, screening_result, matches, nid, discovery_date):
    pdf = ScreeningReportPDF()
    pdf.add_page()
    
    # Subject Information
    pdf.set_font('helvetica', 'B', 14)
    pdf.cell(0, 10, '1. Subject Information', 1, 1, 'L')
    pdf.set_font('helvetica', '', 12)
    pdf.cell(50, 10, 'Name:', 0, 0)
    pdf.cell(0, 10, safe_text(name), 0, 1)
    pdf.cell(50, 10, 'National ID:', 0, 0)
    pdf.cell(0, 10, str(nid), 0, 1)
    pdf.cell(50, 10, 'Screening Date:', 0, 0)
    pdf.cell(0, 10, str(discovery_date), 0, 1)
    pdf.cell(50, 10, 'Status:', 0, 0)
    
    # Status Color code
    label = str(screening_result).upper()
    if 'MATCH' in label:
        pdf.set_text_color(255, 0, 0)
    else:
        pdf.set_text_color(0, 128, 0)
    pdf.cell(0, 10, safe_text(screening_result), 0, 1)
    pdf.set_text_color(0, 0, 0)
    
    pdf.ln(10)
    
    # Match Details
    pdf.set_font('helvetica', 'B', 14)
    pdf.cell(0, 10, '2. Detailed Matches', 1, 1, 'L')
    pdf.ln(5)
    
    if not matches:
        pdf.set_font('helvetica', 'I', 12)
        pdf.cell(0, 10, 'No specific sanction matches found (Clear).', 0, 1)
    else:
        for i, m in enumerate(matches):
            pdf.set_font('helvetica', 'B', 12)
            pdf.cell(0, 10, f'Match #{i+1}: {safe_text(m.get("full_name"))}', 0, 1)
            pdf.set_font('helvetica', '', 11)
            pdf.cell(40, 7, 'Source:', 0, 0)
            pdf.cell(0, 7, f'{safe_text(m.get("source_name"))} ({safe_text(m.get("dataset"))})', 0, 1)
            pdf.cell(40, 7, 'Match Score:', 0, 0)
            pdf.cell(0, 7, f'{m.get("match_score")}%', 0, 1)
            pdf.cell(40, 7, 'Risk Level:', 0, 0)
            pdf.cell(0, 7, f'{m.get("risk_level")}', 0, 1)
            
            # Details/Reason
            details = m.get('details', {})
            reason = details.get('reason') or m.get('reason') or 'N/A'
            pdf.multi_cell(0, 7, f'Reason: {safe_text(reason)}')
            
            if m.get('nationality'):
                pdf.cell(40, 7, 'Nationality:', 0, 0)
                pdf.cell(0, 7, str(m.get('nationality')), 0, 1)
            
            pdf.ln(5)
            if pdf.get_y() > 250:
                pdf.add_page()
    
    # Footer disclaimer
    pdf.set_y(-40)
    pdf.set_font('helvetica', 'I', 9)
    pdf.multi_cell(0, 5, 'Disclaimer: This report is generated automatically based on current sanctions watchlist data. Final compliance decisions should be made by a qualified Compliance Officer.')
    
    # Save PDF
    safe_name = "".join([c for c in str(name) if c.isalnum() or c in (' ', '_')]).rstrip().replace(' ', '_')
    filename = f"Screening_Report_{safe_name}_{datetime.now().strftime('%Y%m%d')}.pdf"
    file_path = os.path.join(OUTPUT_DIR, filename)
    pdf.output(file_path)
    return file_path

def run_report_generation():
    if not os.path.exists(MATCHED_FILE):
        logger.error(f"Input file not found: {MATCHED_FILE}")
        return

    os.makedirs(OUTPUT_DIR, exist_ok=True)
    
    logger.info("Loading matched names...")
    df = pd.read_excel(MATCHED_FILE)
    logger.info(f"Loaded {len(df)} records for report generation.")
    
    # Initialize Engine to get fresh match details
    cfg = get_config()
    db_config = {'database': cfg.DATABASE}
    screener = MultiSourceScreener(db_config)
    
    generated_count = 0
    
    try:
        for index, row in df.iterrows():
            name = row.get('Merchant Name')
            if not name:
                continue
                
            logger.info(f"Processing report for: {name} ({index+1}/{len(df)})")
            
            # Re-screen to get detailed matches list (cached)
            res = screener.screen_person(name=name, entity_type='ENTITY', include_media=False)
            
            matches = res.get('matches', [])
            result_label = res.get('screening_result', row.get('Screening Result', 'POTENTIAL MATCH'))
            nid = row.get('NID', 'N/A')
            discovery_date = row.get('Discovery Date', datetime.now().strftime('%Y-%m-%d'))
            
            try:
                path = generate_pdf_report(name, result_label, matches, nid, discovery_date)
                logger.info(f"Generated: {path}")
                generated_count += 1
            except Exception as e:
                logger.error(f"Failed to generate PDF for {name}: {e}")
                
    finally:
        screener.close()
        
    logger.info(f"Successfully generated {generated_count} reports in {OUTPUT_DIR}")

def safe_text(text):
    """Fallback to transliteration for Arabic text if it causes PDF errors"""
    if not text: return ""
    # Simple check for Arabic characters
    if any('\u0600' <= c <= '\u06FF' for c in str(text)):
        from screening.complynex_engine import transliterate_arabic
        return transliterate_arabic(str(text))
    return str(text)

if __name__ == "__main__":
    run_report_generation()
