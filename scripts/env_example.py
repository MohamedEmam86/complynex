"""P6-4: every setting the code reads from the environment, documented in .env.example.

    scripts/env_example.py --write            # (re)write .env.example from the code
    scripts/env_example.py --check [.env]     # names in the code but missing from a .env, and the reverse
                                              # (prints NAMES only, never values)
"""
import argparse
import os
import re
import sys

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP_DIRS = {'venv', '.git', 'node_modules', '__pycache__', 'tests', 'data', 'logs', 'static'}
PAT = re.compile(r"""(?:os\.getenv|os\.environ\.get|environ\.get|os\.environ\[|getenv)\(\s*['"]([A-Z][A-Z0-9_]{2,})['"]"""
                 r"""|os\.environ\[\s*['"]([A-Z][A-Z0-9_]{2,})['"]\s*\]""")
SECRET = re.compile(r'(PASS|SECRET|TOKEN|KEY|SALT|PRIVATE|CREDENTIAL|DSN)', re.I)
GROUPS = [
    ('Core / Flask', ('FLASK', 'SECRET_KEY', 'APP_', 'SERVER_NAME', 'BASE_URL', 'SITE', 'DEBUG', 'ENV', 'DEMO')),
    ('Database (PostgreSQL)', ('POSTGRES', 'DB_', 'DATABASE', 'PG')),
    ('Tenancy (P6-1)', ('TENANCY', 'MAINT_DB')),
    ('Search (Elasticsearch / semantic)', ('ES_', 'ELASTIC', 'SEMANTIC', 'FAISS')),
    ('Redis / cache / rate limits', ('REDIS', 'CACHE', 'RATELIMIT', 'LIMITER')),
    ('E-mail', ('MAIL', 'EMAIL', 'GMAIL', 'SMTP')),
    ('Screening', ('SCREEN', 'GOLD', 'QUALITY', 'BULK', 'ENTITY_LINKS', 'G10', 'WHITELIST', 'LIST_', 'OPENSANCTIONS', 'ADVERSE', 'NEWS', 'MEDIA')),
    ('eKYC', ('EKYC', 'OCR', 'FACE', 'LIVENESS')),
    ('Monitoring (P6-7)', ('OPS_',)),
]


def scan():
    found = {}
    for root, dirs, files in os.walk(BASE):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS and not d.startswith('.')]
        for fn in files:
            if not fn.endswith('.py'):
                continue
            p = os.path.join(root, fn)
            try:
                txt = open(p, encoding='utf-8', errors='ignore').read()
            except Exception:
                continue
            for m in PAT.finditer(txt):
                name = m.group(1) or m.group(2)
                found.setdefault(name, set()).add(os.path.relpath(p, BASE))
    return found


def group_of(name):
    for g, prefixes in GROUPS:
        if any(name.startswith(p) or p in name for p in prefixes):
            return g
    return 'Other'


def render(found):
    out = ['# ComplyNex — environment settings (generated by scripts/env_example.py; names only).',
           '# Copy to .env and fill in. Never commit the real .env. Lines marked [secret] hold',
           '# passwords / keys: generate them per installation and keep them out of chat and e-mail.', '']
    by = {}
    for n in sorted(found):
        by.setdefault(group_of(n), []).append(n)
    for g, _ in GROUPS + [('Other', ())]:
        names = by.get(g)
        if not names:
            continue
        out.append(f'# ---- {g}')
        for n in names:
            files = sorted(found[n])
            where = ', '.join(files[:3]) + (f' (+{len(files) - 3})' if len(files) > 3 else '')
            tag = ' [secret]' if SECRET.search(n) else ''
            out.append(f'# used in: {where}{tag}')
            out.append(f'{n}=')
        out.append('')
    return '\n'.join(out)


def env_names(path):
    names = set()
    try:
        for line in open(path, encoding='utf-8', errors='ignore'):
            m = re.match(r'\s*(?:export\s+)?([A-Z][A-Z0-9_]*)\s*=', line)
            if m:
                names.add(m.group(1))
    except FileNotFoundError:
        pass
    return names


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--write', action='store_true')
    ap.add_argument('--check', nargs='?', const=os.path.join(BASE, '.env'))
    a = ap.parse_args()
    found = scan()
    if a.write:
        with open(os.path.join(BASE, '.env.example'), 'w', encoding='utf-8') as f:
            f.write(render(found))
        print(f'.env.example: {len(found)} settings')
    if a.check:
        have = env_names(a.check)
        print(f'settings read by the code: {len(found)}; names in {a.check}: {len(have)}')
        print('in the code, not in the .env (code default applies):', ', '.join(sorted(set(found) - have)) or '-')
        print('in the .env, not read by any .py file:', ', '.join(sorted(have - set(found))) or '-')
    if not (a.write or a.check):
        print(render(found))


if __name__ == '__main__':
    sys.exit(main())
