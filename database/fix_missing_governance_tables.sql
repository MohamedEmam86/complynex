-- Fix missing governance tables

CREATE TABLE IF NOT EXISTS board_skills_matrix (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    member_id INTEGER,
    assessment_date DATE,
    assessment_period VARCHAR(50),
    financial_expertise INTEGER DEFAULT 0,
    risk_management INTEGER DEFAULT 0,
    compliance_regulatory INTEGER DEFAULT 0,
    technology_digital INTEGER DEFAULT 0,
    strategy_business INTEGER DEFAULT 0,
    human_resources INTEGER DEFAULT 0,
    legal INTEGER DEFAULT 0,
    audit INTEGER DEFAULT 0,
    marketing_sales INTEGER DEFAULT 0,
    operations INTEGER DEFAULT 0,
    banking_finance INTEGER DEFAULT 0,
    payments_fintech INTEGER DEFAULT 0,
    technology INTEGER DEFAULT 0,
    retail INTEGER DEFAULT 0,
    board_experience INTEGER DEFAULT 0,
    committee_chair_experience INTEGER DEFAULT 0,
    crisis_management INTEGER DEFAULT 0,
    stakeholder_management INTEGER DEFAULT 0,
    arabic_proficiency INTEGER DEFAULT 0,
    english_proficiency INTEGER DEFAULT 0,
    other_languages VARCHAR(255),
    has_professional_certifications BOOLEAN DEFAULT 0,
    certifications_list TEXT,
    total_skill_score INTEGER,
    skill_level VARCHAR(50),
    skill_gaps TEXT,
    development_plan TEXT,
    assessed_by INTEGER,
    FOREIGN KEY (member_id) REFERENCES board_members(id),
    FOREIGN KEY (assessed_by) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS independence_declarations (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    member_id INTEGER,
    declaration_date DATE,
    declaration_type VARCHAR(50),
    declaration_period VARCHAR(50),
    no_material_interest BOOLEAN DEFAULT 1,
    no_employment_5years BOOLEAN DEFAULT 1,
    no_relative_employment BOOLEAN DEFAULT 1,
    no_professional_relationship BOOLEAN DEFAULT 1,
    no_significant_business BOOLEAN DEFAULT 1,
    no_remuneration_except_fees BOOLEAN DEFAULT 1,
    no_other_directorships BOOLEAN DEFAULT 1,
    served_less_than_9years BOOLEAN DEFAULT 1,
    criteria_not_met TEXT,
    explanation TEXT,
    independence_status VARCHAR(50),
    reviewed_by INTEGER,
    review_date DATE,
    next_declaration_due DATE,
    declaration_document_path VARCHAR(500),
    FOREIGN KEY (member_id) REFERENCES board_members(id),
    FOREIGN KEY (reviewed_by) REFERENCES users(id)
);
